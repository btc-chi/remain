# Regenerates Rootwork/SeedData.swift: Bryan's prayers from the Slack thread, the verses he asked to keep,
# and the people he prays for. Run from repo root: python ios/tools/gen_seed.py
import re, json

html = open('prototype/rootwork.template.html', encoding='utf-8').read()
V = json.load(open('ios/Rootwork/Resources/verses.json', encoding='utf-8'))

seed = re.search(r'const SEED = \[(.*?)\n\];', html, re.S).group(1)
items = re.findall(r'\{m:"([^"]+)", k:"(\w+)", t:"((?:[^"\\]|\\.)*)"([^}]*)\}', seed)
months = {"July": (2026, 7), "August": (2026, 8), "September": (2026, 9), "Yesterday": (2026, 10)}

# Verses from the Slack thread that he wanted to remember.
KEEP = ["John 14:6", "Psalm 139:8", "Psalm 139:14", "Psalm 118:22", "Matthew 6:25", "Luke 6:31",
        "Philippians 1:21", "John 1:48", "Ephesians 6:13-17", "2 Timothy 4:7-8"]

BS = chr(92)
def swift_str(s):
    return s.replace(BS, BS + BS).replace('"', BS + '"').replace('\n', BS + 'n')

out = [
    'import Foundation', 'import SwiftData', '',
    '/// First-launch import: prayers and reflections from the Slack DM thread, the verses kept from it,',
    '/// and the people prayed for. Generated by tools/gen_seed.py',
    'enum SeedData {',
    '    static func seedIfNeeded(_ ctx: ModelContext) {',
    '        guard (try? ctx.fetchCount(FetchDescriptor<Entry>())) == 0 else { return }',
    '        func at(_ y: Int, _ m: Int, _ d: Int, _ h: Int) -> Date {',
    '            Calendar.current.date(from: DateComponents(year: y, month: m, day: d, hour: h, minute: 12)) ?? .now',
    '        }',
    '',
]
count = {}
for m, k, t, rest in items:
    y, mo = months[m]
    i = count.get(m, 0); count[m] = i + 1
    day = 1 if m == "Yesterday" else min(28, 2 + i * 3)
    hour = [6, 7, 12, 16, 21][i % 5]
    tags = re.search(r'tags:\[([^\]]*)\]', rest)
    tags = tags.group(1) if tags else ''
    shared = '["Ricky"]' if 'shared:"Ricky"' in rest else '[]'
    out.append(f'        ctx.insert(Entry(.{k}, "{t}", tags: [{tags}], createdAt: at({y}, {mo}, {day}, {hour}), sharedWith: {shared}))')
out.append('')
for r in KEEP:
    out.append(f'        ctx.insert(SwordVerse(ref: "{r}", text: "{swift_str(V[r])}"))')
out += [
    '',
    '        ctx.insert(Person(name: "Ricky", relation: "Brother", isBrother: true))',
    '        ctx.insert(Person(name: "My wife", relation: "Wife"))',
    '        ctx.insert(Person(name: "My daughter", relation: "Daughter"))',
    '        try? ctx.save()',
    '    }',
    '}',
    '',
]
open('ios/Rootwork/SeedData.swift', 'w', encoding='utf-8').write('\n'.join(out))
print(f'{len(items)} entries, {len(KEEP)} kept verses, 3 people')
